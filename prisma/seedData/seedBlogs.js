async function seedBlogs() {
  console.log('Seeding initial blog posts...');
  for (const blog of INITIAL_BLOGS) {
    const existing = await prisma.blogPost.findUnique({ where: { slug: blog.slug } });
    if (!existing) {
      await prisma.blogPost.create({ data: blog });
      console.log(`Created blog post: "${blog.title}"`);
    } else {
      console.log(`Blog post already exists: "${blog.title}"`);
    }
  }
  console.log('Blog seeding complete!');
}

module.exports = { seedBlogs };

if (require.main === module) {
  seedBlogs()
    .then(() => process.exit(0))
    .catch((err) => {
      console.error(err);
      process.exit(1);
    });
}
